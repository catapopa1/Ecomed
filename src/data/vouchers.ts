/** A line of the "Pachetul include" / "Ședința include" block. `sessions` only where the voucher prints a count. */
export interface ServiceLine {
  name: string;
  sessions?: number;
  /** VIP vouchers print days, not sessions. */
  days?: number;
}

/** A tick-box option printed on the voucher ("☐ Opțional: …"). Price only where the voucher prints one. */
export interface OptionLine {
  name: string;
  /** Extra text printed with the option, verbatim. */
  note?: string;
  pricePerSession?: number;
}

export type Promo =
  | { type: 'bonusSession' } // "+1 ședință" cadou
  | { type: 'discount'; percent: 20; price: number }; // −20%, rounded down as on the approved slides

export interface Voucher {
  /** As numbered by the owner: '1'…'19', '4.1', 'VIP1', 'VIP2'. */
  id: string;
  group: GroupId;
  /** Order inside the group (as on the social slides). */
  order: number;
  /** Small label above "VOUCHER" on the front. */
  line: 'BEAUTY' | 'RECUPERARE' | 'VIP';
  /** Front title + subtitle, verbatim. */
  title: string;
  subtitle: string;
  /** Short card label from the approved slides. */
  cardTitle: string;
  /** Heading of the back's left block, verbatim. */
  includesLabel: 'Pachetul include' | 'Ședința include' | 'Afecțiuni tratate';
  services?: ServiceLine[];
  /** "Afecțiuni tratate" list, verbatim from the back. */
  conditions?: string[];
  /** "Durata unei ședințe: aproximativ N minute". Absent where the voucher prints none. */
  durationMin?: number;
  options?: OptionLine[];
  /** Extra printed line, verbatim. */
  note?: string;
  /** Normal price in lei. null = "Preț după consult" (the voucher leaves the value blank). */
  price: number | null;
  priceUnit: 'pachet' | 'ședință';
  /** Christmas promo until 7 Jan 2027 (FACTS §5, approved slides). null = no promo. */
  promo: Promo | null;
  validityMonths: 12;
  images: {
    /** Source files in materiale_site (web versions are generated by task S7). */
    front: string;
    back: string;
    drawing: string;
  };
  /** Things to confirm with Cata / the owner before this goes live. */
  todo?: string[];
}

